"""The committed notebook must match its generator, and must be clean.

`notebooks/extract.ipynb` is generated by `scripts/build_notebook.py`. Editing
the notebook in place would make the two drift and would commit execution
counts and outputs along with it.
"""

from __future__ import annotations

import ast
import importlib.util
import json
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
NOTEBOOK = REPO / "notebooks" / "extract.ipynb"
GENERATOR = REPO / "scripts" / "build_notebook.py"


@pytest.fixture(scope="module")
def notebook() -> dict:
    return json.loads(NOTEBOOK.read_text())


@pytest.fixture(scope="module")
def generated() -> dict:
    spec = importlib.util.spec_from_file_location("build_notebook", GENERATOR)
    module = importlib.util.module_from_spec(spec)
    sys.modules["build_notebook"] = module
    spec.loader.exec_module(module)
    return module.build()


def code_cells(notebook: dict) -> list[str]:
    return ["".join(c["source"]) for c in notebook["cells"] if c["cell_type"] == "code"]


def test_the_committed_notebook_matches_its_generator(notebook, generated):
    assert notebook == generated, (
        "notebooks/extract.ipynb is out of date; run `python scripts/build_notebook.py`"
    )


def test_the_notebook_carries_no_outputs_or_execution_counts(notebook):
    for cell in notebook["cells"]:
        if cell["cell_type"] == "code":
            assert cell["outputs"] == []
            assert cell["execution_count"] is None


def test_every_code_cell_parses(notebook):
    for i, source in enumerate(code_cells(notebook)):
        # `%pip` is a notebook magic, not Python.
        stripped = "\n".join(
            "pass" if line.strip().startswith("%") else line
            for line in source.splitlines()
        )
        try:
            ast.parse(stripped)
        except SyntaxError as exc:  # pragma: no cover - only on a real break
            raise AssertionError(f"code cell {i} does not parse: {exc}") from exc


def test_the_notebook_requests_a_gpu_runtime(notebook):
    assert notebook["metadata"]["accelerator"] == "GPU"
    assert notebook["metadata"]["colab"]["gpuType"] == "T4"


SECRET_NAMES = {"token", "HF_TOKEN", "secret"}


def _names_in(node: ast.AST) -> set[str]:
    return {n.id for n in ast.walk(node) if isinstance(n, ast.Name)}


def test_the_notebook_never_prints_the_token(notebook):
    """A secret read from Colab must not reach the notebook's output.

    Checked on the parsed code rather than on the text, so a message that
    merely mentions the words "HF_TOKEN" is fine and passing the variable to
    `print` is not.
    """
    for i, source in enumerate(code_cells(notebook)):
        stripped = "\n".join(
            "pass" if line.strip().startswith("%") else line
            for line in source.splitlines()
        )
        for node in ast.walk(ast.parse(stripped)):
            if not isinstance(node, ast.Call):
                continue
            func = node.func
            name = getattr(func, "id", None) or getattr(func, "attr", None)
            if name not in ("print", "display"):
                continue
            for argument in node.args:
                leaked = _names_in(argument) & SECRET_NAMES
                assert not leaked, f"code cell {i} passes {leaked} to {name}()"


def test_the_notebook_does_not_write_the_token_anywhere(notebook):
    """Only `os.environ` may hold it, and only for this session."""
    joined = "\n".join(code_cells(notebook))
    assert "userdata.get" in joined, "the notebook no longer reads Colab secrets"
    for line in joined.splitlines():
        if "userdata.get" in line:
            assert line.strip().startswith("token ="), line
        if "write_text" in line or "json.dump" in line:
            assert not (_token_words(line) & SECRET_NAMES), line
    assert "del token" in joined, "the token should not outlive the cell that reads it"


def _token_words(line: str) -> set[str]:
    import re

    return set(re.findall(r"[A-Za-z_][A-Za-z_0-9]*", line))


